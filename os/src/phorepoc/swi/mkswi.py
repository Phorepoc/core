"""mkswi.py -- regenerate OUR install server sources from the RCL_3 baseline (src/phorepoc/swi): installserver.mmp (pointing at the
baseline for every file but installmachine.cpp) and installmachine.cpp with the Phorepoc DEVELOPER MODE.

Developer mode (user decision 2026-10-12: a dev device, signing handling undecided -> verification OFF by default, like
RomPatcher's install-server patch): `PhorepocDevMode = true` in Z:\\system\\data\\swipolicy.ini (config/swi/)
makes the install server treat every package as validated to a trust anchor (protected UIDs/SIDs/VIDs, protected dirs and
eclipsing all follow the trust status) and grant every capability the package's binaries request. `false` = stock Symbian
behaviour. The key is read by the install server itself (no change to the securitymanager DLL or its exports).

    py src/phorepoc/swi/mkswi.py      # rewrites installserver.mmp + installmachine.cpp + securityinfo.cpp here; fails loudly if an anchor moved
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
# output dir named like the package: emitter/mmp.py variant_for() picks the S60 product variant (SYMBIAN_UNIVERSAL_INSTALL_FRAMEWORK...)
# by the oss.FCL.sf.mw. path
OUT = os.path.join(HERE, "oss.FCL.sf.mw.appinstall-group")
os.makedirs(OUT, exist_ok=True)
SWI = os.path.join(REPO, "baseline", "symbian-rcl3", "oss.FCL.sf.mw.appinstall", "installationservices", "swi")
REL = os.path.relpath(SWI, OUT).replace("\\", "/")

# ---- installserver.mmp: baseline-relative paths re-rooted; installmachine.cpp from here
mmp = open(os.path.join(SWI, "group", "installserver.mmp"), encoding="utf-8", errors="replace").read()
def reroot(m):
    kw, path = m.group(1), m.group(2)
    if path == ".":
        return f"{kw} {REL}/group"
    return f"{kw} {REL}/group/{path}" if not path.startswith("/") else m.group(0)
mmp = re.sub(r"^(SOURCEPATH|USERINCLUDE)[ \t]+(\S+)", reroot, mmp, flags=re.M | re.I)
assert re.search(r"^SOURCE installmachine\.cpp\s*$", mmp, re.M), "installmachine.cpp not in installserver.mmp"
mmp = re.sub(r"^SOURCE installmachine\.cpp\s*$", "// SOURCE installmachine.cpp  -- OURS copy below (Phorepoc developer mode)", mmp, flags=re.M)
assert re.search(r"^SOURCE securityinfo\.cpp\s*$", mmp, re.M), "securityinfo.cpp not in installserver.mmp"
mmp = re.sub(r"^SOURCE securityinfo\.cpp\s*$", "// SOURCE securityinfo.cpp  -- OURS copy below (VFPv3 runs VFPv2 code)", mmp, flags=re.M)
mmp += "\n// Phorepoc (src/phorepoc/swi/mkswi.py): the install machine with the developer mode\nSOURCEPATH .\nSOURCE installmachine.cpp\nSOURCE securityinfo.cpp\n"
# the [SWI] trace (DEBUG_PRINTF, RDebug) in release builds too: OUR log.h first on the include path + PHOREPOC_SWI_TRACE.
# Without it an install that fails says only KSWInstErrGeneralError (-30478) and the reason is lost.
first = re.search(r"^USERINCLUDE\b", mmp, re.M | re.I)
assert first, "no USERINCLUDE in installserver.mmp"
mmp = mmp[:first.start()] + "USERINCLUDE .   // Phorepoc: log.h with the release-build trace\nMACRO PHOREPOC_SWI_TRACE\n" + mmp[first.start():]
log = open(os.path.join(SWI, "inc", "log.h"), encoding="utf-8", errors="replace").read()
assert log.count("#ifdef _DEBUG") == 1, "log.h _DEBUG anchor moved"
log = log.replace("#ifdef _DEBUG", "#if defined(_DEBUG) || defined(PHOREPOC_SWI_TRACE)   // Phorepoc: the trace in release builds", 1)
old = "#define DEBUG_CODE_SECTION(a) TRAP_IGNORE({ a; }) "
assert old in log, "log.h DEBUG_CODE_SECTION anchor moved"
log = log.replace(old, "#ifdef _DEBUG\n" + old + "\n#else\n#define DEBUG_CODE_SECTION(a)   // Phorepoc: debug-only code stays debug-only\n#endif", 1)
# RawPrint (DebugPrint mode 1) does not reach the board's debug log; RDebug::Printf/Print (mode 0) does
assert log.count("RDebug::RawPrint(buffer);") == 2, "log.h RawPrint anchors moved"
log = log.replace("RDebug::RawPrint(buffer);", "RDebug::Printf(\"%S\", &buffer);   // Phorepoc: mode 0 reaches the debug log", 1)
log = log.replace("RDebug::RawPrint(buffer);", "RDebug::Print(_L(\"%S\"), &buffer);   // Phorepoc: mode 0 reaches the debug log", 1)
open(os.path.join(OUT, "log.h"), "w", newline="\n").write(
    "// log.h -- GENERATED by src/phorepoc/swi/mkswi.py from the RCL_3 baseline: DEBUG_PRINTF also under PHOREPOC_SWI_TRACE\n" + log)
open(os.path.join(OUT, "installserver.mmp"), "w", newline="\n").write(
    "// installserver.mmp -- GENERATED by src/phorepoc/swi/mkswi.py from the RCL_3 baseline (do not edit)\n" + mmp)

# ---- installmachine.cpp
src = open(os.path.join(SWI, "source", "swis", "server", "installmachine.cpp"), encoding="utf-8", errors="replace").read()
HELPER = r'''
// ---- Phorepoc developer mode (src/phorepoc/swi/mkswi.py) -----------------------------------------------------------------
// `PhorepocDevMode = true` in the SWI policy file: every package is trusted and granted what it asks for. Read once.
static TBool PhorepocDevModeL()
	{
	static TInt cached = -1;
	if (cached >= 0)
		return cached;
	cached = 0;
	RFs fs;
	if (fs.Connect() != KErrNone)
		return EFalse;
	RFile f;
	if (f.Open(fs, _L("z:\\system\\data\\swipolicy.ini"), EFileRead | EFileShareReadersOnly) == KErrNone)
		{
		TInt size = 0;
		f.Size(size);
		HBufC8* buf = HBufC8::New(size);
		if (buf)
			{
			TPtr8 p = buf->Des();
			if (f.Read(p) == KErrNone)
				{
				_LIT8(KKey, "PhorepocDevMode");
				TInt at = p.FindF(KKey);
				if (at >= 0)
					{
					TPtrC8 rest = p.Mid(at + KKey().Length());
					TInt eol = rest.Locate('\n');
					if (eol >= 0)
						rest.Set(rest.Left(eol));
					_LIT8(KTrue, "true");
					cached = rest.FindF(KTrue) >= 0 ? 1 : 0;
					}
				}
			delete buf;
			}
		f.Close();
		}
	fs.Close();
	return cached;
	}
'''
anchor = "// Handle signature and certificate validation errors\nCInstallMachine::TState* CInstallMachine::TVerifyControllerState::CompleteL()"
assert anchor in src, "TVerifyControllerState::CompleteL anchor moved"
src = src.replace(anchor, HELPER + "\n" + anchor, 1)

old = "\t// check what was the result of validation\n\tswitch (iInstallMachine.iSigValidationResult)\n\t\t{"
assert old in src, "signature switch anchor moved"
src = src.replace(old,
    "\t// Phorepoc developer mode: whatever the signature result, the package is trusted (as if validated to an anchor)\n"
    "\tif (PhorepocDevModeL())\n"
    "\t\t{\n"
    "\t\tDEBUG_PRINTF2(_L8(\"Install Machine - Phorepoc developer mode: signature result %d treated as trusted\"), iInstallMachine.iSigValidationResult);\n"
    "\t\tiInstallMachine.SetTrust(ESisPackageCertificateChainValidatedToTrustAnchor);\n"
    "\t\tiInstallMachine.SetValidationStatus(EValidatedToAnchor);\n"
    "\t\treturn static_cast<TState*>(&iInstallMachine.iCheckPrerequisitesState);   // (no OCSP: nothing to revoke)\n"
    "\t\t}\n" + old, 1)

old = "void CInstallMachine::CheckAndGrantCapabilitiesL(RPointerArray<CFileDescription>& aFilesToCapabilityCheck)\n\t{"
assert old in src, "CheckAndGrantCapabilitiesL anchor moved"
src = src.replace(old, old +
    "\n\tif (PhorepocDevModeL())   // Phorepoc developer mode: every requested capability is granted\n"
    "\t\t{\n"
    "\t\t(void)aFilesToCapabilityCheck;\n"
    "\t\treturn;\n"
    "\t\t}", 1)
open(os.path.join(OUT, "installmachine.cpp"), "w", newline="\n").write(
    "// installmachine.cpp -- GENERATED by src/phorepoc/swi/mkswi.py: the RCL_3 install machine + the Phorepoc developer mode\n" + src)

# ---- securityinfo.cpp (also built into sisregistryclient and plan: registry/components.py _SWISEC): an executable built for
# VFPv2 was refused unless the HAL reports exactly VFPv2 (KErrWrongHeaderFormat, -10258); a VFPv3 CPU (EFpTypeVFPv3 /
# EFpTypeVFPv3D16 from K::FloatingPointTypes) executes VFPv2 code and the loader takes it
src = open(os.path.join(SWI, "source", "swis", "server", "securityinfo.cpp"), encoding="utf-8", errors="replace").read()
old = "\t\tif (VFPHardware!=EFpTypeVFPv2 && info.iHardwareFloatingPoint==EFpTypeVFPv2)"
assert old in src, "VFP check anchor moved"
src = src.replace(old,
    "\t\tif (VFPHardware!=EFpTypeVFPv2 && VFPHardware!=EFpTypeVFPv3 && VFPHardware!=EFpTypeVFPv3D16\n"
    "\t\t\t&& info.iHardwareFloatingPoint==EFpTypeVFPv2)", 1)
open(os.path.join(OUT, "securityinfo.cpp"), "w", newline="\n").write(
    "// securityinfo.cpp -- GENERATED by src/phorepoc/swi/mkswi.py: the RCL_3 file + a VFPv3 CPU takes VFPv2 executables\n" + src)
print("mkswi: installserver.mmp + installmachine.cpp + securityinfo.cpp written")
