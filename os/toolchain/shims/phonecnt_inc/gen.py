"""gen.py -- OURS: regenerate the forwarding headers in this directory.

The RCL_3 phone package's PhoneCntFinder exports its API into the PACKAGE's own inc/ (bld.inf
`|../../../inc/<name>`), not epoc32/include, so the mw clients that include it (vmbxengine) find
nothing. One forwarding header per such export, named as the export destination (lower case: the
container file system is case-sensitive), including the real file by a relative path.

    PHOREPOC_SYMBIAN=<the Symbian source> python3 os/toolchain/shims/phonecnt_inc/gen.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SYMBIAN = os.environ.get("PHOREPOC_SYMBIAN") or os.path.join(HERE, "..", "..", "..", "..", "symbian")
GROUP = os.path.join(SYMBIAN, "symbian-rcl3", "oss.FCL.sf.app.phone", "phoneengine",
                     "PhoneCntFinder", "Group")

for line in open(os.path.join(GROUP, "bld.inf"), encoding="utf-8", errors="replace"):
    m = re.match(r"\s*(\S+)\s*\|\s*\.\./\.\./\.\./inc/(\S+)", line)
    if not m:
        continue
    src = os.path.normpath(os.path.join(GROUP, m.group(1)))
    rel = os.path.relpath(src, SYMBIAN).replace(os.sep, "/")   # included from the source root: <symbian-rcl3/...>
    with open(os.path.join(HERE, m.group(2)), "w", newline="\n") as fh:
        fh.write("/* Copyright The Phorepoc Authors\n * SPDX-License-Identifier: EPL-2.0 OR GPL-2.0-or-later */\n\n"
                 "// OURS: forwarding header (generated by gen.py) -- the RCL_3 phone package exports this\n"
                 "// into its own inc/ (PhoneCntFinder bld.inf), not epoc32/include\n"
                 f'#include <{rel}>\n')
    print(m.group(2))
