# Regenerates os/data/charconv/generatedcpp/g_<stem>.cpp -- the conversion tables of the charconv plug-ins -- the way
# the 2010 build's syslibs/generate_cpp extension does: for every "start extension syslibs/generate_cpp" block of
# charconvplugins/group/bld.inf (TYPE cpp or all; dat-only blocks are skipped), run
#   perl cnvtool.pl data/<stem><CTL_EXT>.ctl data/<stem>.txt g_<stem>.cpp -generateSourceCode <EXTRA_PARAMS>
# The registry's charconv plug-in entries take these files in place of the mmp's /epoc32/build/generatedcpp sources.
# Needs perl. The 2010 PARSER.pm uses defined(@array), which modern perl rejects: patched in a temporary copy.
#   usage: gen_cpp.sh <path to the fetched oss.FCL.sf.os.textandloc/charconvfw>
set -e
here="$(cd "$(dirname "$0")" && pwd)"
S="${1:?path to .../oss.FCL.sf.os.textandloc/charconvfw}"
OUT="$here/../../data/charconv/generatedcpp"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
cp "$S/charconv_fw/tools/PARSER.PM" "$T/PARSER.pm"; cp "$S/charconv_fw/tools/WRITER.PM" "$T/WRITER.pm"
cp "$S/charconvplugins/tools/cnvtool.pl" "$T/"
sed -i 's/defined(@PARSER::nextNonEmptyStrippedDownLine) && //' "$T/PARSER.pm"
mkdir -p "$OUT"
D="$S/charconvplugins/data"
# one line per block: TYPE|CTL_EXT|EXTRA_DEP|EXTRA_PARAMS|stems...
python3 - "$S/charconvplugins/group/bld.inf" > "$T/blocks.txt" <<'EOF'
import re, sys
t = open(sys.argv[1], encoding="utf-8", errors="replace").read().replace("\\\n", " ")
for blk in re.findall(r"start\s+extension\s+syslibs/generate_cpp(.*?)\n\s*end\b", t, re.I | re.S):
    o = {}
    for line in blk.splitlines():
        line = line.split("//", 1)[0].strip()
        m = re.match(r"option\s+(\w+)\s*(.*)", line, re.I)
        if m:
            o[m.group(1).upper()] = m.group(2).strip()
    print("|".join([o.get("TYPE", "cpp"), o.get("CTL_EXT", ""), o.get("EXTRA_DEP", ""), o.get("EXTRA_PARAMS", ""), o.get("STEMS", "")]))
EOF
n=0
while IFS='|' read -r type ctlext dep params stems; do
  [ "$type" = dat ] && continue
  dep="${dep//\$(SOURCE_DIRECTORY)\$/$D}"
  params="${params//\$(EXTRA_DEP)/$dep}"
  for s in $stems; do
    # EXTRA_PARAMS words are separate arguments (the makefile quotes each)
    ctl=$(find "$D" -maxdepth 1 -iname "$s$ctlext.ctl" | head -1); txt=$(find "$D" -maxdepth 1 -iname "$s.txt" | head -1)   # bld.inf case != disk case
    [ -n "$ctl" ] && [ -n "$txt" ] || { echo "gen_cpp: $s: no .ctl/.txt" >&2; exit 1; }
    (cd "$T" && perl -I. cnvtool.pl "$ctl" "$txt" "$OUT/g_$s.cpp" -generateSourceCode $params) >/dev/null 2>"$T/warn.txt" || { cat "$T/warn.txt" >&2; exit 1; }
    # cnvtool's header names the output path and stamps today's year: a stable header instead (the tables are Nokia-derived data)
    sed -i -e "1s|.*|// g_$s.cpp -- generated by os/tools/charconv/gen_cpp.sh (cnvtool.pl) from charconvplugins/data/$s.txt|" \
           -e "3s|.*|// Portions Copyright (c) Nokia Corporation and/or its subsidiary(-ies). All rights reserved.|" \
           -e "3a // SPDX-License-Identifier: EPL-2.0 OR GPL-2.0-or-later" "$OUT/g_$s.cpp"
    n=$((n+1))
  done
done < "$T/blocks.txt"
echo "gen_cpp: $n tables -> $OUT"
